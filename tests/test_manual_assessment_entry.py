    def test_same_session_b10_correction_invalidates_old_context_without_rebinding_origin(self):
        body = self.body(self.context())
        self.assertIsNotNone(importlib.util.find_spec("session_metadata_revision"),
                             "DEPENDENCY: verified B10 publisher/current-context integration required")
        revisions = importlib.import_module("session_metadata_revision")
        state = revisions.read_metadata_state(self.service.index, SID)
        changed = metadata()
        changed.update(laterality="left", confirmed_at="2026-10-29T16:01:00+00:00")
        original = (self.folder / "session.json").read_bytes()
        run_hash = sha256_file(self.folder / "run.json")
        revisions.publish_metadata_revision(
            self.service.index, SID, metadata=changed,
            expected_origin_sha256=state["origin"]["sha256"],
            expected_head_sha256=None if state["head"] is None else state["head"]["sha256"],
            operation_id="b" * 32, reason_code="operator_correction", confirm=True)
        current = self.context()
        self.assertNotEqual(current["metadata_context_sha256"], body["metadata_context_sha256"])
        self.assertEqual((self.folder / "session.json").read_bytes(), original)
        self.assertEqual(sha256_file(self.folder / "run.json"), run_hash)
        self.refused(body, "MANUAL_ASSESSMENT_CONTEXT_CHANGED")

