    @staticmethod
    def write(path, value):
        path.write_text(json.dumps(value, allow_nan=False, sort_keys=True), encoding="utf-8")

    def _start_server(self, service):
        dist = self.base / ("TEST_ONLY-dist-" + str(len(list(self.base.glob("TEST_ONLY-dist-*")))))
        dist.mkdir()
        (dist / "index.html").write_text("<title>TEST_ONLY</title>", encoding="utf-8")
        samples = dist / "TEST_ONLY-samples"
        samples.mkdir()
        server = make_server(service, token=TOKEN, dist=dist, samples=samples, port=0)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        self.addCleanup(self._stop_server, server, thread)
        self.server, self.port = server, server.server_port

    @staticmethod
    def _stop_server(server, thread):
        server.shutdown()
        server.server_close()
        thread.join(timeout=4)

    def request(self, method, action, body=None, *, session_id=SID, authenticated=True, headers=None):
        connection = http.client.HTTPConnection("127.0.0.1", self.port, timeout=6)
        try:
            request_headers = {"Host": f"127.0.0.1:{self.port}"}
            if authenticated:
                request_headers.update(Authorization="Bearer " + TOKEN,
                                       Origin=f"http://127.0.0.1:{self.port}")
            if body is not None:
                request_headers["Content-Type"] = "application/json"
            request_headers.update(headers or {})
            payload = json.dumps(body, allow_nan=False).encode() if isinstance(body, dict) else body
            connection.request(method, f"/api/v1/sessions/{session_id}/{action}", payload, request_headers)
            response = connection.getresponse()
            return response.status, json.loads(response.read())
        finally:
            connection.close()

    def context(self):
        status, value = self.request("GET", "manual-assessment-context")
        self.assertEqual(status, 200, ("R06 route/eligibility business RED", value))
        self.assertEqual(value["schema"], CONTEXT_SCHEMA)
        self.assertEqual(value["session_id"], SID)
        self.assertEqual(value["status"], "AVAILABLE")
        for field in ("context_sha256", "metadata_context_sha256", "origin_sha256", "run_sha256"):
            self.assertRegex(value[field], r"^[0-9a-f]{64}$")
        self.assertEqual(value["origin_sha256"], sha256_file(self.folder / "session.json"))
        self.assertEqual(value["run_sha256"], sha256_file(self.folder / "run.json"))
        self.assertIs(value["test_only"], True)
        self.assertIs(value["clinical_accuracy_validated"], False)
