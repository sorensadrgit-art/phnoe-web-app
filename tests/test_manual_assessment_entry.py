    def body(self, context, kind="gait", operation="1" * 32):
        item = next(entry for entry in context["input_sets"] if entry["kind"] == kind)
        labels = ([{"frame_index": 50, "side": "left", "event_type": "initial_contact"},
                   {"frame_index": 70, "side": "left", "event_type": "toe_off"}]
                  if kind == "gait" else [{"start_frame": 50, "bottom_frame": 73, "end_frame": 97}])
        return {"operation_id": operation, "context_sha256": context["context_sha256"],
                "metadata_context_sha256": context["metadata_context_sha256"],
                "input_id": item["input_id"], "source_sha256": item["source_sha256"],
                "reviewer": "TEST_ONLY analytic fixture; no human reviewer",
                "annotation_origin": "human_observed_video_frames", "labels": labels,
                "tolerance_frames": 3, "confirm": True}

    @staticmethod
    def snapshot(folder, held=None):
        result = {}
        for path in sorted(folder.rglob("*")):
            relative = path.relative_to(folder).as_posix()
            identity = path.stat()
            if path.is_file():
                if held is not None and relative == ANCHOR:
                    position = held.tell()
                    try:
                        held.seek(0)
                        raw = held.read()
                    finally:
                        held.seek(position)
                else:
                    raw = path.read_bytes()
                result[relative] = (identity.st_dev, identity.st_ino, hashlib.sha256(raw).hexdigest())
            else:
                result[relative + "/"] = (identity.st_dev, identity.st_ino)
        return result

    def refused(self, body, reason, *, held=None, session_id=SID, raw=None):
        before = self.snapshot(self.folder, held)
        audit = self.service.index.verify_audit()
        status, result = self.request("POST", "manual-assessments", body if raw is None else raw,
                                      session_id=session_id)
        self.assertEqual(status, 409, result)
        self.assertIn(reason, json.dumps(result))
        self.assertEqual(self.snapshot(self.folder, held), before, "refusal must precede every file/directory write")
        self.assertEqual(self.service.index.verify_audit(), audit)

