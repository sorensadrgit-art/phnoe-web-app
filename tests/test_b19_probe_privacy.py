"""TEST_ONLY generated probe/HTTP fixtures; no native codec, recording or device call."""
from __future__ import annotations

import http.client
import io
import json
import subprocess
import tempfile
import threading
import traceback
import unittest
from contextlib import contextmanager, redirect_stderr
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import Mock, patch

from capture_station import check_readiness, probe_clip
from t6_server import make_server
from t6_service import IntegratedService


class B19ProbePrivacyTests(unittest.TestCase):
    token = "generated-b19-probe-http-token-000000000000000000000000"
    fixed = "VIDEO_INVALID: video probe failed; original preserved"
    private = ("B19_PROBE_PRIVATE_SYNTHETIC token=generated-probe-private-token "
               r"C:\Users\GeneratedProbePrivateUser\generated-private-probe.mp4")

    def setUp(self):
        temporary = tempfile.TemporaryDirectory(prefix="b19-probe-generated-")
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.projects = self.root / "projects"
        self.projects.mkdir()
        self.ui = self.root / "ui"
        self.ui.mkdir()
        (self.ui / "index.html").write_text("TEST_ONLY", encoding="utf-8")

    def private_error(self, kind):
        if kind is subprocess.CalledProcessError:
            error = kind(1, ["ffprobe", self.private], output=self.private, stderr=self.private)
        elif kind is subprocess.TimeoutExpired:
            error = kind(["ffprobe", self.private], 25, output=self.private, stderr=self.private)
        elif kind is json.JSONDecodeError:
            error = kind(self.private, self.private, 0)
        else:
            error = kind(self.private)
        error.add_note("B19_PROBE_PRIVATE_SYNTHETIC_NOTE")
        error.__cause__ = ValueError("B19_PROBE_PRIVATE_SYNTHETIC_CAUSE")
        return error

    @staticmethod
    def probe_payload(**overrides):
        stream = {"codec_type": "video", "width": 1280, "height": 720,
                  "duration": "2.0", "avg_frame_rate": "30/1", "nb_frames": "60",
                  "tags": {"rotate": "0"}}
        stream.update(overrides)
        return {"streams": [stream], "format": {"duration": "2.0"}}

    def redacted(self, value):
        for forbidden in ("B19_PROBE_PRIVATE_SYNTHETIC", "generated-probe-private-token",
                          "GeneratedProbePrivateUser", "generated-private-probe.mp4",
                          str(self.root)):
            self.assertNotIn(forbidden, value)

    def diagnostic(self, records, exception_type):
        self.assertEqual(len(records), 1)
        record = records[0]
        self.assertIn("event=capture_probe_failed", record.getMessage())
        self.assertIn("exception_type=" + exception_type, record.getMessage())
        self.assertEqual(record.levelname, "WARNING")
        self.assertEqual(record.pathname, "capture_station.py")
        self.assertEqual(record.funcName, "probe_clip")
        self.assertIsNone(record.exc_info)
        self.assertIsNone(record.stack_info)
        self.assertIsNone(record.exc_text)
        self.redacted(str(record.__dict__))

    @contextmanager
    def server(self, service):
        server = make_server(service, token=self.token, dist=self.ui, samples=self.ui, port=0)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            yield server
        finally:
            server.shutdown()
            server.server_close()
            thread.join(timeout=4)
            self.assertFalse(thread.is_alive(), "Generated HTTP fixture must stop")

    def get_capture(self, server):
        connection = http.client.HTTPConnection("127.0.0.1", server.server_port, timeout=4)
        try:
            connection.request("GET", "/api/v1/sessions/draft/capture", headers={
                "Host": f"127.0.0.1:{server.server_port}",
                "Authorization": "Bearer " + self.token,
            })
            response = connection.getresponse()
            return response.status, response.read().decode("utf-8")
        finally:
            connection.close()

    def test_P1_probe_caught_failures_hide_filename_native_text_and_chained_traceback(self):
        source = self.root / "generated-private-probe.mp4"
        source.write_bytes(b"TEST_ONLY generated bytes, not actual video")
        before = source.read_bytes()
        classes = (OSError, PermissionError, FileNotFoundError, ValueError,
                   ZeroDivisionError, KeyError, StopIteration, IndexError,
                   subprocess.CalledProcessError, subprocess.TimeoutExpired, json.JSONDecodeError)
        scenarios = [(kind.__name__, self.private_error(kind), None) for kind in classes]
        scenarios.extend((
            ("malformed_numeric_width", None, self.probe_payload(width=self.private)),
            ("invalid_geometry", None, self.probe_payload(width=1)),
            ("invalid_fps", None, self.probe_payload(avg_frame_rate="0/1")),
            ("invalid_duration", None, self.probe_payload(duration="nan")),
        ))
        for name, error, payload in scenarios:
            with self.subTest(case=name):
                runner = Mock(side_effect=error) if error is not None else Mock(
                    return_value=SimpleNamespace(stdout=json.dumps(payload)))
                with (patch("capture_station.subprocess.run", runner),
                      self.assertLogs("capture_station", level="WARNING") as log):
                    with self.assertRaises(ValueError) as caught:
                        probe_clip(source)
                    # The producer refuses without exposing a filename or native error text.
                    self.assertEqual(str(caught.exception), self.fixed)
                    self.assertTrue(caught.exception.__suppress_context__)
                    self.assertIsNone(caught.exception.__cause__)
                    self.redacted("".join(traceback.format_exception(caught.exception)))
                    expected_type = type(error).__name__ if type(error) in (
                        OSError, PermissionError, FileNotFoundError, ValueError) else "OtherException"
                    if error is None:
                        expected_type = "ValueError"
                    self.diagnostic(log.records, expected_type)
                runner.assert_called_once()
                self.assertEqual(source.read_bytes(), before)

    def test_P2_actual_http_capture_finalization_failure_preserves_partial_and_cached_status(self):
        project = self.projects / "draft"
        (project / "raw").mkdir(parents=True)
        config = project / "Config.toml"
        config.write_bytes(b"# TEST_ONLY generated project\n")
        partial = project / "raw" / "cam02_board.part.mp4"
        partial.write_bytes(b"TEST_ONLY unverified generated partial")
        original = partial.read_bytes()
        service = IntegratedService(projects_root=self.projects)
        self.addCleanup(service.close)
        process = SimpleNamespace(poll=Mock(return_value=0), stdin=Mock())
        service.webcam = {"session": "draft", "role": "cam02_board", "process": process}
        stderr = io.StringIO()
        with (redirect_stderr(stderr), self.server(service) as server,
              patch("capture_station.subprocess.run", side_effect=self.private_error(OSError)) as run,
              self.assertLogs("capture_station", level="WARNING") as log):
            status, body = self.get_capture(server)
            self.assertEqual(status, 200)
            result = json.loads(body)
            self.assertEqual(result["state"], "failed")
            self.assertEqual(result["message"], self.fixed)
            self.assertEqual(result["session_id"], "draft")
            self.assertEqual(result["role"], "cam02_board")
            self.redacted(body + stderr.getvalue())
            self.assertEqual(partial.read_bytes(), original)
            self.assertFalse((project / "raw" / "cam02_board.mp4").exists())
            self.assertEqual(config.read_bytes(), b"# TEST_ONLY generated project\n")
            self.assertFalse((project / "session.json").exists())
            self.assertIsNone(service.webcam)
            process.stdin.close.assert_called_once()
            cached_status, cached_body = self.get_capture(server)
            self.assertEqual(cached_status, 200)
            self.assertEqual(json.loads(cached_body), result)
            run.assert_called_once()
            self.diagnostic(log.records, "OSError")

    def test_P3_real_readiness_exposes_only_fixed_issue_and_preserves_raw_source(self):
        project = self.projects / "readiness"
        (project / "raw").mkdir(parents=True)
        config = project / "Config.toml"
        config.write_bytes(b"# TEST_ONLY generated project\n")
        source = project / "raw" / "cam01_trial.mp4"
        source.write_bytes(b"TEST_ONLY generated raw original")
        original = source.read_bytes()
        with (patch("capture_station.subprocess.run",
                    side_effect=self.private_error(subprocess.CalledProcessError)) as run,
              self.assertLogs("capture_station", level="WARNING") as log):
            report = check_readiness(project, inspect_existing=True)
            self.assertIn(self.fixed, report["issues"])
            self.assertFalse(report["ready_to_register"])
            # Session path is an existing explicit readiness identity; only error issues are tested here.
            self.redacted(json.dumps(report["issues"]))
            self.assertEqual(source.read_bytes(), original)
            self.assertEqual(config.read_bytes(), b"# TEST_ONLY generated project\n")
            self.assertFalse((project / "session.json").exists())
            run.assert_called_once()
            self.diagnostic(log.records, "OtherException")

    def test_P4_valid_probe_metadata_and_original_bytes_remain_unchanged(self):
        source = self.root / "valid-generated-control.mp4"
        source.write_bytes(b"TEST_ONLY generated parser fixture, not actual video")
        before = source.read_bytes()
        with patch("capture_station.subprocess.run", return_value=SimpleNamespace(
                stdout=json.dumps(self.probe_payload()))) as run:
            result = probe_clip(source)
        self.assertEqual(result, {"width": 1280, "height": 720, "rotation": 0,
                                  "fps": "30/1", "duration": 2.0, "frame_count": 60})
        self.assertEqual(source.read_bytes(), before)
        run.assert_called_once()
        self.assertEqual(run.call_args.args[0][-1], str(source))
        self.assertEqual(run.call_args.kwargs, {
            "capture_output": True, "text": True, "encoding": "utf-8", "timeout": 25, "check": True,
        })


if __name__ == "__main__":
    unittest.main()
