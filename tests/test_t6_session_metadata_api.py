"""Real loopback API over generated identities/files; no participant capture proof."""
from __future__ import annotations

import copy
import http.client
import json
import tempfile
import threading
import unittest
from pathlib import Path
from unittest.mock import patch

from session_contract import ROLES, load_session, sha256_file
from t6_server import make_server
from t6_service import IntegratedService


def generated_metadata():
    return {
        "schema": "kinelab.session-metadata.v1",
        "subject_id": "sub-11111111111111111111111111111111",
        "operator_id": "op-22222222222222222222222222222222",
        "task_id": "generated-squat", "protocol_id": "generated-protocol",
        "protocol_version": "1", "laterality": "bilateral",
        "confirmed": True, "confirmed_at": "2026-10-29T10:00:00+00:00",
    }


class SessionMetadataApiTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.projects = self.root / "projects"
        self.projects.mkdir()
        self.service = IntegratedService(projects_root=self.projects)
        self.addCleanup(self.service.close)
        dist = self.root / "dist"
        dist.mkdir()
        (dist / "index.html").write_text("<title>Generated KineLab API fixture</title>", encoding="utf-8")
        samples = self.root / "samples"
        samples.mkdir()
        self.server = make_server(self.service, token="a" * 50, dist=dist, samples=samples, port=0)
        self.port = self.server.server_port
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()
        self.addCleanup(self.stop_server)

    def stop_server(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=4)

    def auth(self):
        return {"Authorization": "Bearer " + "a" * 50,
                "Origin": f"http://127.0.0.1:{self.port}"}

    def post(self, path, body, *, headers=None):
        connection = http.client.HTTPConnection("127.0.0.1", self.port, timeout=6)
        try:
            request_headers = {"Host": f"127.0.0.1:{self.port}", "Content-Type": "application/json"}
            request_headers.update(headers or {})
            connection.request("POST", path, json.dumps(body).encode("utf-8"), request_headers)
            response = connection.getresponse()
            payload = response.read()
            return response.status, json.loads(payload)
        finally:
            connection.close()

    def create(self, session_id, **kwargs):
        return self.post("/api/v1/sessions", {"id": session_id, "kind": "real", **kwargs}, headers=self.auth())

    def test_http_metadata_roundtrips_into_draft_and_immutable_registration(self):
        metadata = generated_metadata()
        status, response = self.create("api-confirmed", metadata=metadata)
        self.assertEqual(status, 201, response)
        self.assertEqual(response["id"], "api-confirmed")
        project = self.projects / "api-confirmed"
        template = project / "session-template.json"
        self.assertEqual(json.loads(template.read_text(encoding="utf-8"))["metadata"], metadata)
        self.assertFalse((project / "session.json").exists())

        # Generated byte fixtures exercise real hashing/registration, not video or hardware readiness.
        for role in ROLES:
            (project / "raw" / (role + ".mp4")).write_bytes(("generated API fixture " + role).encode())
        sources = [project / "Config.toml", template, *(project / "raw").glob("*.mp4")]
        before = {path: path.read_bytes() for path in sources}
        endpoint = "/api/v1/sessions/api-confirmed/register"
        status, response = self.post(endpoint, {}, headers=self.auth())
        self.assertEqual(status, 409, response)
        self.assertFalse((project / "session.json").exists())
        # Only the hardware readiness check is isolated; HTTP/service/library/producer remain real.
        with patch("session_library._check_readiness_locked", return_value={
                "ready_to_register": True, "issues": [], "missing": []}):
            status, response = self.post(endpoint, {"confirm": True}, headers=self.auth())
        self.assertEqual(status, 200, response)
        registered = load_session(project)
        self.assertEqual(registered["metadata"], metadata)
        for role, capture in registered["captures"].items():
            self.assertEqual(capture["sha256"], sha256_file(project / "raw" / (role + ".mp4")))
        original_manifest = (project / "session.json").read_bytes()
        status, response = self.post(endpoint, {"confirm": True}, headers=self.auth())
        self.assertEqual(status, 409, response)
        self.assertEqual((project / "session.json").read_bytes(), original_manifest)
        for path, original in before.items():
            self.assertEqual(path.read_bytes(), original)

    def test_absent_and_null_metadata_preserve_existing_callers(self):
        for session_id, fields in [("api-legacy", {}), ("api-null", {"metadata": None})]:
            with self.subTest(session_id=session_id):
                status, response = self.create(session_id, **fields)
                self.assertEqual(status, 201, response)
                project = self.projects / session_id
                self.assertNotIn("metadata", json.loads((project / "session-template.json").read_text(encoding="utf-8")))
                self.assertFalse((project / "session.json").exists())

    def test_invalid_explicit_metadata_creates_no_project(self):
        invalid = [[], False, "opaque", {}, {**generated_metadata(), "real_name": "generated disallowed field"}]
        for key, value in [("subject_id", "generated real-name string"), ("operator_id", "generated@example.invalid"),
                           ("confirmed", 1), ("confirmed", False), ("confirmed_at", "2026-10-29"),
                           ("protocol_version", 1), ("schema", "kinelab.session-metadata.v99")]:
            bad = copy.deepcopy(generated_metadata())
            bad[key] = value
            invalid.append(bad)
        for index, metadata in enumerate(invalid):
            session_id = f"api-invalid-{index}"
            with self.subTest(session_id=session_id):
                status, response = self.create(session_id, metadata=metadata)
                self.assertEqual(status, 409, response)
                self.assertIn("SESSION_METADATA_INVALID", json.dumps(response))
                self.assertFalse((self.projects / session_id).exists())

    def test_service_direct_caller_forwards_optional_metadata(self):
        response = self.service.create_session("api-direct", metadata=generated_metadata())
        self.assertEqual(response["id"], "api-direct")
        template = self.projects / "api-direct" / "session-template.json"
        self.assertEqual(json.loads(template.read_text(encoding="utf-8"))["metadata"], generated_metadata())

    def test_metadata_does_not_bypass_http_access_or_capture_gates(self):
        payload = {"id": "api-denied", "kind": "real", "metadata": generated_metadata()}
        for headers, expected in [({}, 401), ({**self.auth(), "Origin": "https://example.invalid"}, 403),
                                  ({**self.auth(), "Host": "example.invalid"}, 400)]:
            with self.subTest(expected=expected, headers=list(headers)):
                status, response = self.post("/api/v1/sessions", payload, headers=headers)
                self.assertEqual(status, expected, response)
                self.assertFalse((self.projects / "api-denied").exists())
        status, response = self.create("api-capture-blocked", metadata=generated_metadata())
        self.assertEqual(status, 201, response)
        with patch("t6_service.subprocess.Popen") as process:
            status, response = self.post("/api/v1/sessions/api-capture-blocked/capture",
                                         {"role": "cam02_trial", "seconds": 12, "confirm": True}, headers=self.auth())
        self.assertEqual(status, 409, response)
        self.assertIn("PARTICIPANT_RECORDING_BLOCKED", json.dumps(response))
        process.assert_not_called()


if __name__ == "__main__":
    unittest.main()
