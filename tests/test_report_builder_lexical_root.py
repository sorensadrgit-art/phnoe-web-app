"""TEST_ONLY constructor admission with real filesystem aliases; no media or GUI."""
import errno
import tempfile
import unittest
from pathlib import Path

from report_builder import ReportBuilder
from session_index import SessionIndex


class ReportBuilderLexicalRootTests(unittest.TestCase):
    def setUp(self):
        owned = tempfile.TemporaryDirectory(prefix="TEST_ONLY-report-root-")
        self.addCleanup(owned.cleanup)
        self.root = Path(owned.name).absolute()
        self.projects = self.root / "projects"
        self.projects.mkdir()
        (self.projects / "TEST_ONLY-sentinel.txt").write_bytes(b"original generated bytes\n")
        self.control = self.root / "ordinary-control"
        self.control.mkdir()
        self.index = SessionIndex(self.root / "supplied-index.db", self.projects)
        self.addCleanup(self.index.close)

    def snapshot(self):
        return {p.relative_to(self.root).as_posix() + ("/" if p.is_dir() else ""):
                None if p.is_dir() else p.read_bytes()
                for p in self.root.rglob("*")}

    def alias(self, target):
        owned = tempfile.TemporaryDirectory(prefix="TEST_ONLY-report-root-alias-")
        self.addCleanup(owned.cleanup)
        link = Path(owned.name).absolute() / "linked-root"
        try:
            link.symlink_to(target, target_is_directory=True)
        except NotImplementedError as error:
            self.skipTest("real directory symlink unsupported: " + str(error))
        except OSError as error:
            if getattr(error, "winerror", None) == 1314 or error.errno in (
                    errno.EPERM, errno.EACCES, errno.ENOTSUP):
                self.skipTest("real directory symlink unavailable on host: " + str(error))
            raise
        self.addCleanup(link.unlink, missing_ok=True)
        self.assertTrue(link.is_symlink())
        self.assertEqual(link.resolve(), target.resolve())
        return link

    def ordinary_controls(self):
        original = (self.projects / "TEST_ONLY-sentinel.txt").read_bytes()
        supplied = ReportBuilder(self.projects, self.index)
        self.assertIs(supplied.index, self.index)
        self.assertEqual(supplied.projects_root, self.projects.resolve())
        owned = ReportBuilder(self.control)
        try:
            self.assertEqual(owned.projects_root, self.control.resolve())
            self.assertEqual(owned.index.projects_root, self.control.resolve())
            self.assertEqual(owned.index.query_sessions(), [])
        finally:
            owned.index.close()
        self.assertEqual((self.projects / "TEST_ONLY-sentinel.txt").read_bytes(), original)

    def test_ordinary_constructor_paths_keep_both_index_modes(self):
        self.ordinary_controls()

    def test_leaf_and_ancestor_aliases_refused_before_owned_index_creation(self):
        self.ordinary_controls()
        leaf = self.alias(self.projects)
        ancestor = self.alias(self.root)
        for spelling in (leaf, ancestor / self.projects.name):
            with self.subTest(spelling=spelling):
                before = self.snapshot()
                unexpected = None
                try:
                    with self.assertRaisesRegex(ValueError, "TAKE_RECOVERY_UNKNOWN"):
                        unexpected = ReportBuilder(spelling)
                finally:
                    if unexpected is not None:
                        unexpected.index.close()
                    self.assertEqual(self.snapshot(), before)
                    self.assertFalse((self.projects / ".kinelab_index.db").exists())
                    self.assertTrue(leaf.is_symlink())
                    self.assertTrue(ancestor.is_symlink())

    def test_leaf_and_ancestor_aliases_refused_with_supplied_index(self):
        self.ordinary_controls()
        leaf = self.alias(self.projects)
        ancestor = self.alias(self.root)
        for spelling in (leaf, ancestor / self.projects.name):
            with self.subTest(spelling=spelling):
                before = self.snapshot()
                try:
                    with self.assertRaisesRegex(ValueError, "TAKE_RECOVERY_UNKNOWN"):
                        ReportBuilder(spelling, self.index)
                finally:
                    self.assertEqual(self.snapshot(), before)
                    self.assertTrue(leaf.is_symlink())
                    self.assertTrue(ancestor.is_symlink())
        self.assertEqual(self.index.query_sessions(), [])
