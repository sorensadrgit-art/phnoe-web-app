def _scoring_entry(reason="Current scoring producers omit source/reference binding."):
    entry = {field: "UNAVAILABLE" for field in (
        "missed_reference_count", "unscorable_reference_count", "false_candidate_count",
        "by_event_type", "phase_boundary_disagreement_count", "incomplete_attempts")}
    entry.update(status="BLOCKED_UNBOUND_SCORING", reason=reason,
                 artifact="manual-scoring.json", artifact_sha256="UNAVAILABLE")
    return entry


def _plan_doc(gait=None, squat=None, scoring=None, issues=None, board=None,
              runs=None, sources=None):
    """A doc shaped exactly like the JSON report dict that _build_pdf consumes."""
    present = any(value is not None for value in (gait, squat, scoring)) or bool(issues)
    event_analysis = {
        "status": ("TEST_ONLY_CANDIDATE_EVIDENCE_NOT_PHYSICAL_VALIDATION" if present
                   and not issues else
                   "BLOCKED_INVALID_OR_UNBOUND_EVENT_EVIDENCE" if issues else
                   "UNAVAILABLE"),
        "gait_candidates": gait if gait is not None else "UNAVAILABLE",
        "squat_candidates": squat if squat is not None else "UNAVAILABLE",
        "manual_scoring": scoring if scoring is not None else "UNAVAILABLE",
        "artifact_issues": list(issues or []),
        "note": ("Stored candidates are generated/test-only, unvalidated evidence."
                 if present or issues else
                 "No stored event-analysis artifacts found; event confidence is unavailable."),
    }
    passport = {"kind": "demo", "state": "TEST_ONLY", "badge": "TEST ONLY",
                "captured_count": 0, "history": [], "is_test_only": True,
                "board_measurement": board, "sources": sources or {},
                "runs": runs or {}}
    return {
        "schema": "kinelab.research-report.v1", "session_id": "b16-plan",
        "generated_at_utc": "2026-10-30T00:00:00+00:00", "is_test_only": True,
        "watermark": "TEST ONLY - NOT PHYSICAL VALIDATION", "state": "TEST_ONLY",
        "clinical_accuracy_verified": False, "physical_accuracy_verified": False,
        "measurement_count": 0, "event_analysis": event_analysis,
        "measurement_status": "No valid measurements", "motion_sha256": None,
        "provenance": {"software": "KineLab PT local software candidate",
                       "pose2sim_version": "unavailable",
                       "opensim_version": "unavailable",
                       "onnxruntime_version": "unavailable"},
        "passport": passport, "sources": passport["sources"],
        "board_measurement": board, "runs": passport["runs"],
        "limitations": ("Internal research software only. Physical camera geometry and "
                        "clinical accuracy unverified without physical measurement "
                        "evidence and independent reference validation."),
    }


