def _gait_doc_with(candidate_count):
    """Validated-shape gait artifact with candidate_count rows (frame_index < 100)."""
    doc = copy.deepcopy(GAIT_CANDIDATES_DOC)
    template = doc["candidates"][0]
    doc["candidates"] = []
    for index in range(candidate_count):
        item = copy.deepcopy(template)
        item["frame_index"] = index
        item["side"] = "left" if index % 2 == 0 else "right"
        item["event_type"] = ("candidate_initial_contact" if index % 2 == 0
                              else "candidate_toe_off")
        doc["candidates"].append(item)
    doc["candidate_count"] = candidate_count
    return doc


def _squat_doc_with(rep_count):
    doc = copy.deepcopy(SQUAT_CANDIDATES_DOC)
    template = doc["repetitions"][0]
    doc["repetitions"] = []
    for index in range(rep_count):
        item = copy.deepcopy(template)
        item["start_frame"] = 5 + index * 20
        item["bottom_frame"] = item["start_frame"] + 6
        item["end_frame"] = item["start_frame"] + 12
        doc["repetitions"].append(item)
    doc["candidate_repetition_count"] = rep_count
    return doc


def _plan_text(pages):
    return "\n".join(op.get("s", "") for page in pages for op in page
                     if op.get("kind") == "text")


def _tagged(pages, kind):
    return [(page_index, op["tag"]) for page_index, page in enumerate(pages)
            for op in page
            if isinstance(op.get("tag"), tuple) and op["tag"] and op["tag"][0] == kind]


