"""PROPOSED: mounted TEST_ONLY registered/manual/current-v2 report exercise.

Generated noncodec source bytes, generated native-contract records and analytic
labels. No camera, decoder, inference, human observation or clinical proof.
"""
import json
from pathlib import Path
from unittest.mock import patch

SID = "TEST_ONLY-browser-manual-reports"


def prepare_fixture(service):
    # These are existing repository-only test producers, never app dependencies.
    from gait_events import orient_event_candidates, propose_extrema
    from native_evidence_fixture import complete_native_fixture
    from run_pipeline import validate_run_evidence
    from session_contract import ROLES, load_session, sha256_file
    from session_metadata_revision import publish_metadata_revision, read_metadata_state
    from setup_project import register_captures
    from squat_events import analyze_squats
    from test_manual_assessment_entry import metadata
    from test_manual_assessment_provenance import generated_trajectory
    from test_squat_events import fixture_reps

    folder = service.index.projects_root / SID
    (folder / "raw").mkdir(parents=True, exist_ok=False)
    (folder / "Config.toml").write_text("# TEST_ONLY generated\n[project]\n", encoding="utf-8")
    for role in ROLES:
        (folder / "raw" / f"{role}.mp4").write_bytes(("TEST_ONLY non-codec " + role).encode())
    initial = metadata()
    (folder / "session-template.json").write_text(json.dumps({
        "schema": "kinelab.session-template.v1", "session_id": SID,
        "kind": "demo", "metadata": initial}, allow_nan=False), encoding="utf-8")
    session = register_captures(folder, SID, metadata=initial, kind="demo")
    assert load_session(folder)["session_id"] == SID
    provenance = {
        "schema": "kinelab.generated-assessment-fixture.v1", "session_id": SID, "kind": "demo",
        "test_only": True, "source_video_decoded": False, "human_observation": "NOT_PERFORMED",
        "native_compute": "NOT_PERFORMED", "physical_accuracy": "UNVERIFIED",
        "clinical_validation": "UNVERIFIED",
        "captures_sha256": {role: source["sha256"] for role, source in session["captures"].items()},
        "producers_sha256": {name: sha256_file(Path(__file__).resolve().parents[1] / name) for name in (
            "tools/verify_report_browser.py", "tests/native_evidence_fixture.py",
            "tests/test_manual_assessment_provenance.py", "tests/test_squat_events.py")},
    }
    provenance_path = folder / "generated-fixture-provenance.json"
    provenance_path.write_text(json.dumps(provenance, sort_keys=True, separators=(",", ":"), allow_nan=False),
                               encoding="utf-8")
    with (folder / "Config.toml").open("a", encoding="utf-8") as stream:
        stream.write("# kinelab-generated-provenance-sha256=" + sha256_file(provenance_path) + "\n")
    complete_native_fixture(folder, "", through="poseEstimation")
    validate_run_evidence(folder, through="poseEstimation")
    source = session["captures"]["cam01_trial"]["sha256"]
    gait = generated_trajectory(source)
    gait_candidates = orient_event_candidates(propose_extrema(
        gait, "cam01_trial", source, image_width=1024, image_height=576),
        screen_forward="right")
    squat = fixture_reps(1)
    squat["source_sha256"] = source
    squat_candidates = analyze_squats(squat, "cam01_trial", source, camera_view="side",
                                     activity_confirmed=True, image_width=1024, image_height=576)
    for kind, trajectory, candidates in (("gait", gait, gait_candidates),
                                         ("squat", squat, squat_candidates)):
        directory = folder / "assessment-inputs" / ("TEST_ONLY-" + kind)
        directory.mkdir(parents=True)
        for name, value in (("trajectory", trajectory), ("candidates", candidates)):
            (directory / (name + ".json")).write_text(
                json.dumps(value, sort_keys=True, allow_nan=False), encoding="utf-8")
    originals = {name: sha256_file(folder / name) for name in (
        "session.json", "session-template.json", "Config.toml", "run.json", "generated-fixture-provenance.json",
        *(f"raw/{role}.mp4" for role in ROLES))}
    # The only doubled native observation: generated bytes are not decodable video.
    with patch("session_index.probe_clip", return_value={
            "width": 1024, "height": 576, "fps": 30, "duration": 8}):
        service.index.reindex()
    state = read_metadata_state(service.index, SID)
    assert service.index.get_passport(SID)["is_test_only"] is True
    assert state["status"] == "AVAILABLE" and state["head"] is None
    corrected = dict(initial, operator_id="op-" + "3" * 32)
    receipt = publish_metadata_revision(
        service.index, SID, metadata=corrected,
        expected_origin_sha256=state["origin"]["sha256"], expected_head_sha256=None,
        operation_id="a" * 32, reason_code="operator_correction", confirm=True)
    current = read_metadata_state(service.index, SID)
    assert current["status"] == "AVAILABLE" and current["metadata"] == corrected
    assert current["context_sha256"] == receipt["context_sha256"]
    assert all(sha256_file(folder / name) == digest for name, digest in originals.items())
    return {"session_id": SID, "kind": "GENERATED_CONTRACT_FIXTURE_ONLY",
            "source_video_decoded": False, "human_observation": "NOT_PERFORMED",
            "native_compute": "NOT_PERFORMED", "test_only": True,
            "physical_accuracy": "UNVERIFIED", "clinical_validation": "UNVERIFIED",
            "originals_sha256": originals, "metadata_context_sha256": current["context_sha256"]}


def run_checks(browser, evaluate, wait_for, service, output, checks, reopen):
    from manual_assessment_entry import manual_assessment_context
    from report_generation import committed_reports, current_report_context
    from session_contract import sha256_file
    from session_metadata_revision import read_metadata_state

    folder = service.index.projects_root / SID
    # This scenario refuses to degrade to the old unregistered synthetic case.
    state = read_metadata_state(service.index, SID)
    assert state["status"] == "AVAILABLE" and state["head"] is not None
    before = {path.relative_to(folder).as_posix(): sha256_file(path)
              for path in folder.rglob("*") if path.is_file()}
    browser("select", '[aria-label="Select active session"]', SID)
    wait_for("document.querySelector('[aria-label=\"Select active session\"]').value===" + json.dumps(SID))
    browser("scrollintoview", ".uw-nav-link:has-text('Reports')")
    browser("find", "role", "button", "click", "--name", "Reports Local evidence and exports")
    wait_for("!!document.querySelector('.uw-report-studio form[aria-label=\"Manual reference entry\"]')")
    form = '.uw-report-studio form[aria-label="Manual reference entry"]'
    context = manual_assessment_context(service.index, SID)
    assert context["metadata_context_sha256"] == state["context_sha256"]
    assert {item["kind"] for item in context["input_sets"]} == {"gait", "squat"}
    assert evaluate("document.querySelector(" + json.dumps(form + ' [name="manual_reviewer"]') + ").value")== ""
    assert evaluate("document.querySelectorAll(" + json.dumps(form + ' input[name^="manual_frame_"]') + ").length") == 0
    published = []
    for kind in ("gait", "squat"):
        context = manual_assessment_context(service.index, SID)
        item = next(item for item in context["input_sets"] if item["kind"] == kind)
        wait_for("Array.from(document.querySelector(" + json.dumps(form + ' [name="manual_input_id"]') +
                 ").options).some(o=>o.value===" + json.dumps(item["input_id"]) + ")")
        browser("select", form + ' [name="manual_input_id"]', item["input_id"])
        browser("find", "role", "button", "click", "--name", "Add annotation", "--exact")
        if kind == "gait":
            browser("fill", form + ' [name="manual_frame_0"]', "50")
            browser("select", form + ' [name="manual_side_0"]', "left")
            browser("select", form + ' [name="manual_event_0"]', "initial_contact")
        else:
            for name, value in (("start", "50"), ("bottom", "73"), ("end", "97")):
                browser("fill", form + f' [name="manual_{name}_0"]', value)
        browser("fill", form + ' [name="manual_reviewer"]', "TEST_ONLY automation; no human reviewer")
        browser("fill", form + ' [name="manual_tolerance_frames"]', "3")
        # Simulate these declarations solely to test TEST_ONLY software controls.
        browser("check", form + ' [name="manual_human_observed"]')
        browser("check", form + ' [name="manual_confirmed"]')
        browser("find", "role", "button", "click", "--name", "Publish manual reference", "--exact")
        wait_for("document.querySelector(" + json.dumps(form) + ").textContent.includes('TEST_ONLY server publication receipt:')")
        current = manual_assessment_context(service.index, SID)
        assert len(current["assessments"]) == len(published) + 1
        assert not current["unavailable_assessments"]
        published = current["assessments"]
    checks["mounted_manual_reference_publications"] = published
    evaluate("""window.confirm=()=>true;window.__reportRequests=[];
const original=window.fetch;window.fetch=async(...args)=>{const r=await original(...args);
if(String(args[0]).includes('/artifact/'))window.__reportRequests.push({status:r.status});return r;};""")
    browser("find", "role", "button", "click", "--name", "Generate Offline Research Reports", "--exact")
    wait_for("document.body.textContent.includes(" + json.dumps(SID + "-research-report.pdf") + ")")
    reports = [item for item in service.reports(SID) if item["type"] == "research_report"]
    assert len(reports) == 3 and len(committed_reports(service.index, SID)) == 3
    # Read actual audited publication and its immutable manifest; do not synthesize one.
    events = service.index.conn.execute(
        "SELECT details_json FROM audit_events WHERE session_id=? AND event_type='REPORT_PUBLISHED'", (SID,)).fetchall()
    assert len(events) == 1
    publication = json.loads(events[0]["details_json"])
    assert publication["schema"] == "kinelab.report-publication.v2"
    manifest_path = folder / "exports" / publication["generation"] / "manifest.json"
    assert sha256_file(manifest_path) == publication["manifest_sha256"]
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["schema"] == "kinelab.report-generation.v2" and manifest["supersedes"] is None
    current = current_report_context(service.index, SID)
    assert manifest["metadata_context_sha256"] == state["context_sha256"]
    assert manifest["report_context_sha256"] == current["report_context_sha256"]
    assert manifest["manual_assessment_context"] == current["manual_assessment_context"]
    summary = next(item for item in reports if item["filename"].endswith("-research-summary.json"))
    summary = json.loads(service.artifact(SID, summary["key"]).read_text(encoding="utf-8"))
    assert summary["is_test_only"] is True
    assert summary["clinical_accuracy_verified"] is False and summary["physical_accuracy_verified"] is False
    assert summary["measurement_count"] == 0 and summary["motion_sha256"] is None
    assert summary["metadata_context_sha256"] == state["context_sha256"]
    assert summary["effective_metadata"] == state["metadata"]
    downloaded = []
    for item in reports:
        browser("snapshot", "-i")
        row = evaluate("Array.from(document.querySelectorAll('.uw-report-row')).findIndex(r=>r.querySelector('strong')?.textContent===" + json.dumps(item["filename"]) + ")")
        assert row >= 0
        selector = f".uw-report-row:nth-child({row + 1}) button"
        browser("scrollintoview", selector)
        destination = output / item["filename"]
        browser("click", selector)
        browser("wait", "--download", str(destination))
        expected = sha256_file(service.artifact(SID, item["key"]))
        assert sha256_file(destination) == expected
        downloaded.append({"filename": item["filename"], "bytes": destination.stat().st_size, "sha256": expected})
    assert evaluate("window.__reportRequests") == [{"status": 200}] * 3
    assert evaluate("window.__cameraRequests") == 0
    assert all(sha256_file(folder / name) == digest for name, digest in before.items())
    service.index.verify_audit()
    checks["current_v2_publication"] = publication
    checks["three_actual_downloads_match_committed_generation"] = downloaded
    checks["fixture_limits"] = {"test_only": True, "source_video_decoded": False,
                               "human_observation": "NOT_PERFORMED", "physical_accuracy": "UNVERIFIED",
                               "clinical_validation": "UNVERIFIED", "real_browser_zoom": "NOT_RUN"}
    browser("screenshot", str(output / "TEST_ONLY-manual-report-downloads.png"))
    assert not browser("errors").get("errors", [])
